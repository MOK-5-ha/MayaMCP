"""Pydantic schemas and structured rubrics for Vertex AI and Antigravity evaluation."""

from pydantic import BaseModel, ConfigDict, Field


class TrajectoryEvaluationRubric(BaseModel):
    """Pydantic schema for Agent-as-a-Judge trajectory and multi-turn reasoning evaluation."""

    model_config = ConfigDict(extra="forbid")

    multi_hop_synthesis_score: int = Field(
        ge=1,
        le=5,
        description="Depth of multi-step connections and conversational context synthesis (1=poor, 5=excellent).",
    )
    context_precision_score: int = Field(
        ge=1,
        le=5,
        description="Relevance and precision of retrieved memory/drink knowledge (1=poor, 5=excellent).",
    )
    faithfulness_score: int = Field(
        ge=1,
        le=5,
        description="Adherence to retrieved facts, bartender persona, and recipe ground truth (1=poor, 5=excellent).",
    )
    trajectory_soundness_score: int = Field(
        ge=1,
        le=5,
        description="Efficiency and correctness of tool execution path and phase transitions (1=poor, 5=excellent).",
    )
    reasoning_justification: str = Field(
        min_length=10,
        description="Detailed step-by-step reasoning and scoring justification.",
    )
    is_fallback: bool = Field(
        default=False,
        description="Flag indicating whether this verdict was generated by a heuristic fallback.",
    )


class PointwiseEvaluationRubric(BaseModel):
    """Pydantic schema for single-turn or single-metric pointwise evaluation."""

    model_config = ConfigDict(extra="forbid")

    score: int = Field(
        ge=1,
        le=5,
        description="Overall grade from 1 (poor / severe hallucination) to 5 (excellent / completely grounded).",
    )
    explanation: str = Field(
        min_length=5,
        description="Detailed rationale justifying the assigned score.",
    )
    is_fallback: bool = Field(
        default=False,
        description="Flag indicating whether this verdict was generated by a heuristic fallback.",
    )
